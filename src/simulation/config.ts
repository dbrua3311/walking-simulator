import { z } from "zod";
import type { Config } from "./types";
const number = (min: number, max: number) =>
  z.number().finite().min(min).max(max);
export const configSchema = z.object({
  searchMethod: z.enum(["adaptive", "covariance"]).default("adaptive"),
  controllerModel: z
    .enum([
      "timed-rnn",
      "local-feedback-rnn",
      "local-periodic-rnn",
      "shared-reflex",
      "shared-direction",
      "shared-anatomical",
    ])
    .default("timed-rnn"),
  rewardModel: z
    .enum([
      "temporal-curriculum-v4",
      "supported-curriculum-v5",
      "cycle-curriculum-v6",
      "rhythmic-curriculum-v7",
      "mobile-curriculum-v8",
    ])
    .default("temporal-curriculum-v4"),
  name: z.string().trim().min(1).max(80),
  seed: number(0, 4294967295).int(),
  population: number(2, 60).int(),
  duration: number(1, 60),
  target: number(0.1, 100),
  mutation: number(0, 1),
  crossover: number(0, 1),
  mutationScale: number(0.001, 0.5),
  adaptiveSearch: z.boolean(),
  initialization: z.enum(["random", "weak-balance"]).default("random"),
  initialBalanceBias: number(0, 1).default(0),
  parentCount: number(1, 60).int(),
  curriculum: z.object({
    balanceSeconds: number(0.1, 10),
    steppingFeet: number(2, 4).int(),
    steppingSteps: number(2, 20).int(),
    steppingForward: number(0.01, 0.5),
    coordinatedPromotion: z.boolean().default(false),
    promotionGenerations: number(1, 10).int(),
    forwardSeconds: number(0.1, 50),
    forwardContinuousSeconds: number(0, 50).default(0),
    requireWalkingAtFinish: z.boolean().default(false),
    useDriftLimits: z.boolean().default(false),
    mobileSupportRatio: number(0, 1).default(0),
    minJointFreedomAtPromotion: number(0, 1).default(0),
    maxLateralDeviation: number(0.05, 2).default(0.3),
    maxHeadingDeviation: number(0.1, Math.PI).default(0.35),
    // Missing keys retain the former jump-only flight limit for old files.
    maxWalkingFlightTime: number(0, 0.5).default(0.5),
    maxLateralTravel: number(0.05, 2),
    maxYawTravel: number(0.1, 10),
  }),
  physics: z.object({
    dt: z.literal(1 / 120),
    gravity: number(-20, -1),
    friction: number(0, 2),
    hipTorque: number(0, 50),
    kneeTorque: number(0, 50),
    maxSpeed: number(0.1, 15),
    jointDamping: number(0, 5),
    velocityIterations: number(12, 20).int(),
    positionIterations: number(4, 10).int(),
  }),
  robot: z.object({
    width: number(0.3, 1),
    height: number(0.1, 0.3),
    depth: number(0.15, 0.4),
    coxa: number(0.025, 0.1),
    upper: number(0.1, 0.4),
    lower: number(0.1, 0.4),
    footRadius: number(0.02, 0.06),
    torsoMass: number(1, 10),
    upperMass: number(0.1, 1),
    lowerMass: number(0.1, 1),
  }),
  evaluation: z.object({
    contactModel: z.enum(["proximity", "load-bearing"]).default("proximity"),
    minHeight: number(0.1, 0.5),
    stepMemory: number(0.5, 10),
    walkingContinuityGrace: number(0, 0.2).default(0),
    maxAirTime: number(0.03, 0.5),
    maxVerticalSpeed: number(0.1, 2),
    maxTilt: number(0.3, 1.4),
    tiltGrace: number(0.1, 1),
    warmup: number(0, 5),
    stallWindow: number(1, 10),
    stallDistance: number(0.001, 0.2),
    footGrace: number(0.05, 0.5),
    maxHeightMargin: number(0.05, 0.3),
  }),
});
